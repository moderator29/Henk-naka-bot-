-- =============================================================================
-- Aurora · realtime publication
-- Live notifications (and DMs) need their tables in the supabase_realtime
-- publication so Postgres change events reach subscribed clients. Idempotent:
-- only adds a table if it isn't already published.
-- =============================================================================

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'notifications'
  ) then
    alter publication supabase_realtime add table public.notifications;
  end if;

  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'messages'
  ) then
    alter publication supabase_realtime add table public.messages;
  end if;
end $$;
